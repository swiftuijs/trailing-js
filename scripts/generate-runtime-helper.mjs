import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { format, resolveConfig } from 'prettier';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../packages/twill/package.json', import.meta.url));
const { parse } = require('acorn');
const source = readFileSync(
  new URL('../packages/runtime/src/helpers/v1.js', import.meta.url),
  'utf8',
);
const ast = parse(source, { ecmaVersion: 'latest', sourceType: 'module' });
const exported = ast.body.find(
  (node) => node.type === 'ExportNamedDeclaration' && node.declaration?.id?.name === 'runDefers',
);
assert(
  exported?.declaration.type === 'FunctionDeclaration',
  'Expected one native runDefers function',
);
const fn = exported.declaration;
const names = ['stack', 'failed', 'failure', 'cleanup', 'error'];
assert.deepEqual(
  fn.params.map((node) => node.name),
  ['stack'],
);
const slots = new Map();
function visit(node, parent, key) {
  if (!node?.type) return;
  // Native member/property names and strings are not variable references.
  if (parent?.type === 'MemberExpression' && key === 'property' && !parent.computed) return;
  if (parent?.type === 'Property' && key === 'key' && !parent.computed) return;
  if (node.type === 'Property' && node.shorthand) {
    const value = node.value.type === 'AssignmentPattern' ? node.value.left : node.value;
    if (names.includes(value.name))
      slots.set(value.start, {
        start: value.start,
        end: value.end,
        name: value.name,
        prefix: value.name + ': ',
      });
  }
  if (node.type === 'Identifier' && names.includes(node.name) && !slots.has(node.start))
    slots.set(node.start, { start: node.start, end: node.end, name: node.name, prefix: '' });
  for (const [childKey, value] of Object.entries(node)) {
    for (const child of Array.isArray(value) ? value : [value])
      if (child?.type) visit(child, node, childKey);
  }
}
visit(fn.body);
let cursor = fn.body.start + 1;
const parts = [];
for (const slot of [...slots.values()].sort((a, b) => a.start - b.start)) {
  parts.push(JSON.stringify(source.slice(cursor, slot.start)));
  if (slot.prefix) parts.push(JSON.stringify(slot.prefix));
  parts.push(`names.${slot.name}`);
  cursor = slot.end;
}
parts.push(JSON.stringify(source.slice(cursor, fn.body.end - 1)));
const expression = parts.join(' + ');
const generated = await format(
  `// Generated by scripts/generate-runtime-helper.mjs from runtime helper ABI v1.\n// Source SHA-256: ${createHash('sha256').update(source).digest('hex')}\n// Edit packages/runtime/src/helpers/v1.js, then regenerate.\nexport function syncDeferBody(names: Record<${names.map((name) => JSON.stringify(name)).join(' | ')}, string>): string {\nreturn ${expression};\n}`,
  {
    ...(await resolveConfig(
      fileURLToPath(new URL('../packages/twill/src/defer-helper.ts', import.meta.url)),
    )),
    plugins: [],
    parser: 'typescript',
  },
);
const filename = new URL('../packages/twill/src/defer-helper.ts', import.meta.url);
if (process.argv.includes('--check')) {
  assert.equal(
    readFileSync(filename, 'utf8'),
    generated,
    'Inline runtime helper is stale; run node scripts/generate-runtime-helper.mjs',
  );
} else writeFileSync(filename, generated);
